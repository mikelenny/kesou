("工具酶",
 "基因工程的工具酶主要包括限制酶和DNA连接酶。限制酶能识别双链DNA中特定的核苷酸序列，并在特定部位切割磷酸二酯键，产生黏性末端或平末端。\n"
 "DNA连接酶能将两个DNA片段的磷酸二酯键连接起来，恢复被限制酶切开的缺口。E·coli DNA连接酶只能连接黏性末端，T₄ DNA连接酶既能连接黏性末端也能连接平末端。\n"
 "易错点：限制酶切割的是磷酸二酯键，不是氢键；限制酶具有专一性，一种限制酶只识别一种特定序列。"),
("载体",
 "载体是基因工程中用于携带目的基因进入受体细胞的DNA分子。常用载体有质粒、噬菌体和动植物病毒。\n"
 "作为载体需要具备条件：能自我复制，使目的基因稳定存在；具有一个或多个限制酶切割位点，便于插入目的基因；具有标记基因，便于筛选；对受体细胞无害。\n"
 "易错点：载体不一定是环状DNA，噬菌体载体可以是线性的；标记基因的作用是筛选含目的基因的细胞，而不是提供营养。"),
("基因表达载体的组成",
 "基因表达载体是目的基因与载体结合形成的重组DNA分子，其组成包括目的基因、启动子、终止子、标记基因和复制原点。\n"
 "启动子是RNA聚合酶识别和结合的部位，驱动基因转录；终止子使转录在适当位置停止；标记基因用于筛选成功导入载体的受体细胞。\n"
 "易错点：启动子和终止子不属于目的基因，但缺一不可；构建表达载体时，目的基因必须插入启动子和终止子之间。"),
("基因工程的操作步骤",
 "基因工程的基本操作步骤包括：目的基因的获取、基因表达载体的构建、将目的基因导入受体细胞、目的基因的检测与鉴定。\n"
 "获取目的基因的方法有从基因文库中获取、利用PCR扩增和人工合成。导入受体细胞的方法因受体不同而异，如农杆菌转化法用于植物，显微注射法用于动物。\n"
 "易错点：构建基因表达载体是核心步骤；检测目的基因是否插入用DNA分子杂交，检测是否转录用分子杂交，检测是否翻译用抗原—抗体杂交。"),
("PCR技术",
 "PCR即聚合酶链式反应，是一项在体外大量扩增特定DNA片段的技术。其原理是DNA双链复制，需要模板DNA、引物、四种脱氧核苷酸、Taq酶和缓冲液。\n"
 "PCR过程包括变性、复性和延伸三步：高温使DNA双链解开，降温使引物与模板结合，再升温使Taq酶延伸合成新链。循环多次可使目的DNA呈指数扩增。\n"
 "易错点：PCR需要一对引物，分别与两条模板链的3′端结合；Taq酶耐高温，不需要每轮重新加入。"),
("基因工程的应用",
 "基因工程在农业、医药和环保等领域应用广泛。农业上可培育抗虫、抗病、抗旱和品质改良的转基因作物，如转基因抗虫棉。\n"
 "医药上可生产基因工程药物，如胰岛素、干扰素和疫苗；基因诊断可检测致病基因，基因治疗可向患者体内导入正常基因以纠正缺陷。\n"
 "易错点：基因治疗不是修复原有基因，而是导入正常基因；转基因作物的安全性需经过严格评价，不能简单否定或肯定。"),
("蛋白质工程",
 "蛋白质工程是指以蛋白质分子的结构规律及其与生物功能的关系为基础，通过基因修饰或基因合成，对现有蛋白质进行改造，或制造一种新的蛋白质的技术。\n"
 "蛋白质工程的基本途径是：预期蛋白质功能→设计预期蛋白质结构→推测氨基酸序列→找到并改造相应基因。它被称为第二代基因工程。\n"
 "易错点：蛋白质工程直接改造的是基因，而不是蛋白质分子本身；蛋白质工程需要了解蛋白质的空间结构与功能的关系。"),
