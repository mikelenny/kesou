("生物多样性",
 "生物多样性包括基因多样性、物种多样性和生态系统多样性。基因多样性是物种多样性的基础，生态系统多样性为物种多样性提供生存环境。\n"
 "生物多样性是长期自然选择和协同进化的结果，具有直接价值、间接价值和潜在价值。间接价值主要指生态功能，如涵养水源、调节气候。\n"
 "易错点：生物多样性不包括细胞多样性；保护生物多样性不是禁止开发利用，而是合理利用、可持续发展。"),
("生物多样性的价值",
 "生物多样性的价值包括直接价值、间接价值和潜在价值。直接价值指对人类有实用意义的价值，如食用、药用、工业原料和旅游观赏。\n"
 "间接价值指对生态系统起重要调节作用的价值，如森林涵养水源、湿地蓄洪防旱、草地防风固沙，这类价值往往大于直接价值。潜在价值指目前人类尚不清楚的价值。\n"
 "易错点：间接价值不等于没有直接价值；保护生物多样性主要是保护其生态功能，不能只从经济角度衡量。"),
