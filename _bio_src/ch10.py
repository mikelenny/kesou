("遗传密码与密码子",
 "mRNA上决定一个氨基酸的3个相邻碱基叫做密码子。遗传密码共有64种，其中61种编码氨基酸，3种为终止密码子，不编码氨基酸。\n"
 "密码子具有通用性，即几乎所有生物共用一套密码子；还具有简并性，即一种氨基酸可由多种密码子编码，这在一定程度上降低了基因突变对性状的影响。\n"
 "易错点：密码子位于mRNA上，反密码子位于tRNA上；起始密码子也可编码氨基酸，终止密码子不编码氨基酸。"),
