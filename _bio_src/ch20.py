("生态系统的组成",
 "生态系统由非生物的物质和能量、生产者、消费者和分解者组成。生产者主要是绿色植物，能进行光合作用制造有机物，是生态系统的基石。\n"
 "消费者主要是动物，能加快生态系统的物质循环，对植物的传粉和种子传播有重要作用；分解者主要是细菌和真菌，能把有机物分解为无机物。\n"
 "易错点：生产者不一定是绿色植物，如硝化细菌是化能自养生物；分解者不一定是微生物，蚯蚓等腐食动物也属于分解者。"),
("食物链和食物网",
 "食物链是生态系统中各生物之间由于食物关系而形成的一种联系。每条食物链的起点必须是生产者，终点是不被其他动物捕食的动物。\n"
 "食物网是许多食物链彼此交错连接形成的复杂营养关系。食物网越复杂，生态系统抵抗外界干扰的能力越强。\n"
 "易错点：食物链中不包括分解者和非生物物质；一种生物可同时占据多个营养级；营养级是指生物在食物链中的位置，而不是物种的分类等级。"),
("能量流动",
 "能量流动是指生态系统中能量的输入、传递、转化和散失的过程。能量从生产者固定太阳能开始，沿食物链和食物网单向流动、逐级递减。\n"
 "相邻两个营养级之间的能量传递效率一般为10%~20%，其余能量通过呼吸作用以热能散失，或未被利用，或流向分解者。能量金字塔一般呈正金字塔形。\n"
 "易错点：能量传递效率不是个体之间的比例，而是营养级之间的同化量之比；能量不能循环利用，物质可以循环利用。"),
("生态金字塔",
 "生态金字塔包括能量金字塔、数量金字塔和生物量金字塔。能量金字塔表示各营养级所含能量的多少，一定是上窄下宽的正金字塔。\n"
 "数量金字塔一般也是正金字塔，但可能出现倒置，如一棵树上生活着大量昆虫；生物量金字塔在海洋生态系统中可能倒置，因为浮游植物的繁殖速度快、被消耗也快。\n"
 "易错点：只有能量金字塔不会倒置；金字塔的每一层代表一个营养级，而不是一个物种。"),
("物质循环",
 "物质循环是指组成生物体的C、H、O、N、P、S等元素在生物群落与无机环境之间往返运动的过程，具有全球性和循环性。\n"
 "以碳循环为例，CO₂通过光合作用和化能合成作用进入生物群落，通过呼吸作用、分解作用和燃烧返回大气。碳在生物群落内部以含碳有机物形式传递。\n"
 "易错点：物质循环中的“循环”是在全球范围内进行，不是局部的；碳循环失衡会导致温室效应，但碳元素本身不会被耗尽。"),
("信息传递",
 "生态系统中的信息包括物理信息、化学信息和行为信息。物理信息如光、声、温度和磁力；化学信息如植物的生物碱、动物的性外激素；行为信息如蜜蜂的舞蹈、鸟类的求偶炫耀。\n"
 "信息传递的作用包括：有利于生命活动的正常进行，有利于种群的繁衍，能调节种间关系，维持生态系统的稳定。\n"
 "易错点：信息传递往往是双向的，而能量流动是单向的；信息传递不仅存在于同种生物之间，也存在于不同种生物之间。"),
("生态系统的稳定性",
 "生态系统的稳定性是指生态系统所具有的保持或恢复自身结构和功能相对稳定的能力，包括抵抗力稳定性和恢复力稳定性。\n"
 "抵抗力稳定性是指生态系统抵抗外界干扰并使自身结构功能保持原状的能力；恢复力稳定性是指生态系统遭到破坏后恢复原状的能力。二者往往呈负相关。\n"
 "易错点：抵抗力稳定性强的生态系统恢复力稳定性通常较弱，如热带雨林；生态系统稳定性与物种丰富度、食物网复杂程度有关。"),
("生态系统的反馈调节",
 "反馈调节是生态系统自我调节的基础，分为负反馈调节和正反馈调节。负反馈调节使系统偏离稳态的变化得到抑制，从而维持稳定。\n"
 "例如草原上兔数量增多时，草被大量啃食而减少，兔因食物不足数量下降，草又逐渐恢复。正反馈调节则使系统偏离稳态的变化加剧，如水体污染后鱼类死亡、污染进一步加重。\n"
 "易错点：负反馈调节是生态系统自我调节能力的基础；正反馈调节常导致生态系统崩溃，但在某些生理过程中也有意义。"),
