("微生物的培养",
 "微生物培养需要配制适宜的培养基，提供碳源、氮源、水和无机盐等营养物质，并满足微生物对pH、温度和特殊营养的要求。\n"
 "培养过程必须严格无菌操作，包括对培养基和器具灭菌、对操作者双手和操作台消毒、在酒精灯火焰旁接种。接种方法有平板划线法和稀释涂布平板法。\n"
 "易错点：灭菌杀死包括芽孢和孢子在内的全部微生物，消毒只杀死部分微生物；接种环用灼烧灭菌，培养基用高压蒸汽灭菌。"),
("培养基的配制",
 "培养基按物理性质分为固体培养基、液体培养基和半固体培养基；按成分分为天然培养基和合成培养基；按用途分为选择培养基和鉴别培养基。\n"
 "选择培养基通过加入或缺少某种成分，允许特定微生物生长而抑制其他微生物，如加入青霉素筛选真菌；鉴别培养基通过指示剂或显色反应区分不同微生物，如伊红美蓝培养基鉴别大肠杆菌。\n"
 "易错点：固体培养基常用琼脂作凝固剂，琼脂本身不被微生物利用；培养基配制后需先调pH再灭菌。"),
("无菌技术",
 "无菌技术包括消毒和灭菌。消毒是用较为温和的物理或化学方法杀死物体表面或内部的部分微生物，如煮沸消毒、酒精擦拭、紫外线照射。\n"
 "灭菌是用强烈的理化因素杀死所有微生物，包括芽孢和孢子，常用方法有灼烧灭菌、干热灭菌、高压蒸汽灭菌。接种操作应在酒精灯火焰旁进行。\n"
 "易错点：紫外线消毒只适用于空气和物体表面，不能穿透玻璃和液体；高压蒸汽灭菌时冷空气必须排尽，否则达不到灭菌温度。"),
("传统发酵食品的制作",
 "传统发酵技术利用天然存在的微生物进行发酵，如制作果酒、果醋、泡菜和腐乳。果酒制作利用酵母菌的无氧呼吸，果醋制作利用醋酸菌的有氧呼吸。\n"
 "泡菜制作利用乳酸菌的无氧呼吸产生乳酸；腐乳制作利用毛霉等微生物产生的蛋白酶和脂肪酶分解蛋白质和脂肪。传统发酵多为混合菌种发酵，产品风味独特但质量不稳定。\n"
 "易错点：果酒发酵前期需通气促进酵母菌繁殖，后期需密封；泡菜坛要密封并用水封口，防止杂菌污染。"),
("发酵技术",
 "发酵技术是指利用微生物的代谢活动，通过控制发酵条件，大量生产人类所需产品的技术。发酵过程中微生物通过分解有机物获得能量，同时产生代谢产物。\n"
 "发酵方式分为分批发酵和连续发酵。分批发酵操作简单但效率较低，连续发酵可提高设备利用率，但易发生杂菌污染。\n"
 "易错点：发酵不等于无氧呼吸，好氧发酵需要持续供氧；发酵产物既可能是微生物菌体本身，也可能是其代谢产物。"),
("发酵工程的应用",
 "发酵工程广泛应用于食品、医药、化工和农业等领域。食品工业中用于生产酱油、食醋、酸奶、啤酒和面包；医药工业中用于生产抗生素、氨基酸、维生素和干扰素。\n"
 "在农业上，发酵工程可用于生产微生物肥料、微生物农药和饲料添加剂；在环保领域，可用于处理废水和降解污染物。\n"
 "易错点：发酵工程产品不都是食品，青霉素等药物也由发酵工程生产；发酵工程的核心是优良菌种的选育和发酵条件的优化。"),
("发酵条件的控制",
 "发酵条件包括温度、pH、溶氧量、营养物浓度和发酵时间等。温度影响酶的活性，pH影响微生物的生长和代谢产物积累，溶氧量影响好氧微生物的生长。\n"
 "不同微生物的最适条件不同，如醋酸菌最适温度为30~35℃，需要充足氧气；乳酸菌最适温度为室温至40℃，需要无氧环境。发酵过程中需实时监测并调整条件。\n"
 "易错点：发酵条件不仅影响微生物生长速度，还影响代谢产物的种类和产量；溶氧过多或过少都可能导致发酵失败。"),
